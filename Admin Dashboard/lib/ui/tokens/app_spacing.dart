/// Spacing constants used throughout the application. These values
/// correspond to the spacing system defined in the exported Figma theme.
/// Keeping spacing centralised makes it easy to adjust layouts without
/// hunting down magic numbers.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4.0;     // 4px
  static const double sm = 8.0;     // 8px
  static const double md = 12.0;    // 12px
  static const double base = 16.0;  // 16px (sometimes referred to as 1rem)
  static const double lg = 24.0;    // 24px
  static const double xl = 32.0;    // 32px
  static const double xxl = 48.0;   // 48px
}